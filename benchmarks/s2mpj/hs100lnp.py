"""HS100LNP from S2MPJ (CUTEst) as a benchmark experiment, run with SAA-EI,
SoftSAA-EI, standard BO and Latin hypercube sampling.

Generated by benchmarks/generate_s2mpj.py (version 1) from S2MPJ commit
fea6a70048eaad28b13a08703ddbfdbf65cd9c30. Don't edit it: change the generator and
regenerate (ADR 0012).

- The hidden constraint is C1. Its hidden term, the weighted sum of its
  elements, is the unknown equation y = h; the known equations g are S2MPJ's
  constraints with y in place of that term.
- S2MPJ's start:
  X1 = 1, X2 = 2, X3 = 0, X4 = 4, X5 = 0, X6 = 1, X7 = 1.
- The solution v*, IPOPT's from S2MPJ's start, rounded to 6 decimals:
  X1 = 2.330499, X2 = 1.951372, X3 = -0.477541, X4 = 4.365726, X5 = -0.624487,
  X6 = 1.038131, X7 = 1.594227.
- The oracle optimum is f* = 680.6300573, as the problem file states it
  (SOLTN); IPOPT's is 680.63.
- SoftSAA's temperature is 1e-3 if the stated f* is 0, else
  max(1e-3 |f*|, 1e-06): here 0.68063.

Run it, then plot the newest study:

    pixi run benchmark hs100lnp [--n-runs 3 --plot ...]
    pixi run benchmark hs100lnp plot

`pixi run benchmark hs100lnp --help` lists the flags.
"""

import functools

import hybrid_bo as hb

# Problem: S2MPJ's variables, the decision variables within the bounds the rules
# give them (S2MPJ's where finite, else the hull of its start and v*, widened), the
# mechanistic states with S2MPJ's bounds and those as start bounds. y's start bounds
# cover the hidden term's range within them
X2 = hb.Var("X2", lower=0.9513720000000001, upper=3)
X3 = hb.Var("X3", lower=-1.477541, upper=1)
X4 = hb.Var("X4", lower=3, upper=5.365726)
X6 = hb.Var("X6", lower=0, upper=2.038131)
X7 = hb.Var("X7", lower=0, upper=2.594227)
X1 = hb.Var("X1", start=(0, 3.330499))
X5 = hb.Var("X5", start=(-1.624487, 1))
y = hb.Var("y", start=(-338.456368, -41.345868))


def g(v):
    """The known equations, 0 = g: S2MPJ's constraints, with C1's hidden
    term replaced by y."""
    return [
        127 - v.X3 - 5 * v.X5 + v.y,  # C1
        -5 * v.X6
        + 11 * v.X7
        + (-4 * v.X1**2 - v.X2**2 + 3 * (v.X1 * v.X2) - 2 * v.X3**2),  # C4
    ]


def h(v):
    """The unknown equation y = h, hidden from the methods: C1's hidden
    term."""
    return [-2 * v.X1**2 - 3 * (v.X2**2) ** 2 - 4 * v.X4**2]


def f(v):
    """The objective, S2MPJ's."""
    return (
        (-10 + v.X1) ** 2
        + (-12 + v.X2) ** 2 / 0.2
        + (-11 + v.X4) ** 2 / 0.3333333333
        + (
            -10 * v.X6
            - 8 * v.X7
            + (
                10 * (v.X5 * v.X5**2) ** 2
                + (7 * v.X6**2 + (v.X7**2) ** 2 - 4 * v.X6 * v.X7)
                + (v.X3**2) ** 2
            )
        )
    )


system = hb.System(
    u=[X2, X3, X4, X6, X7],
    x=[X1, X5],
    y=[y],
    g=g,
    h_inputs=[X1, X2, X4],
    measured=[y],
)
problem = hb.Problem(system, f=f)

# Measurement: an oracle plays the real system
measure = hb.oracle_measure(system, h, noise_std=0.0)

# The oracle optimum, as the problem file states it: the study measures regret from
# it, the methods never see it
optimum = 680.6300573

# The prior GP of every BO method, which each fits to its own data: a zero mean and an
# output scale times a Matern-5/2 kernel, both fitted within these bounds (in scaled
# units), and no noise, as the measurement has none (the library's jitter keeps the
# kernel matrix invertible)
outputscale = hb.gp.Param(1.0, bounds=(0.1, 10.0))
lengthscale = hb.gp.Param(1.0, bounds=(1e-3, 1e2))
gp = hb.gp.GP(
    mean=hb.gp.Zero(),
    kernel=outputscale * hb.gp.Matern52(lengthscale=lengthscale),
    noise_std=0.0,
)

# Methods: each takes (problem, measure, initial_points, n, rng), where n is the
# number of iterations, or of design points for the baseline. Hybrid BO with SAA-EI
# and with SoftSAA-EI, both with 25d = 125 scenarios
methods = {
    "hybrid_bo": functools.partial(
        hb.hybrid_bo,
        settings=hb.HybridBOSettings(
            gp=gp,
            acquisition=hb.EI(),
            approximation=hb.SAA(n_scenarios=125),
        ),
    ),
    "hybrid_bo_soft": functools.partial(
        hb.hybrid_bo,
        settings=hb.HybridBOSettings(
            gp=gp,
            acquisition=hb.EI(),
            approximation=hb.SoftSAA(temperature=0.68063, n_scenarios=125),
        ),
    ),
    "standard_bo": functools.partial(
        hb.standard_bo, settings=hb.StandardBOSettings(gp=gp, acquisition=hb.EI())
    ),
    "latin_hypercube_sampling": hb.latin_hypercube_sampling,
}

# Configurations: every method with 10d = 50 evaluations, the first 2d + 1 = 11 of
# them initial points
configurations = {
    label: hb.Configuration(method=method, n_evaluations=50, n_initial=11)
    for label, method in methods.items()
}

# The study, which the command line's flags override. Seed None draws a fresh seed,
# which the saved study keeps, so it can be run again exactly
study_settings = hb.StudySettings(n_runs=10, seed=None)

# Where the experiment comes from, recorded in the task list and the artifact
notes = {
    "problem": "HS100LNP",
    "s2mpj_commit": "fea6a70048eaad28b13a08703ddbfdbf65cd9c30",
    "generator_version": "1",
    "hidden_constraint": "C1",
}

# Run or plot from the command line. The oracle measurement is cheap, so the
# iteration figures draw its oracle values
if __name__ == "__main__":
    hb.cli.main(
        problem,
        measure,
        configurations,
        study_settings,
        optimum=optimum,
        true_curves=True,
        notes=notes,
    )
